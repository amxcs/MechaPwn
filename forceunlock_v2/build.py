#!/usr/bin/env python3
"""Build forceunlock_v2.h from the MechaCon patch sources in this directory.

Each <version>.S assembles to the 216-byte plaintext patch block: 4 slot
addresses, 4 slot values, then the body (svc table first) at LOAD + 0x20.
The block is DES-encrypted into the 224-byte NVRAM layout (2 x 112 bytes,
words 400..511) and written as a C array.

    MECHA_PATCH_KEY=<16 hex digits> python3 build.py [--clang] [--check]

--clang  use clang / ld.lld / llvm-objcopy instead of arm-none-eabi-*
--check  compare with the existing forceunlock_v2.h instead of writing it

Requires pycryptodome.
"""
import os
import re
import shutil
import struct
import subprocess
import sys
import tempfile
from pathlib import Path

from Crypto.Cipher import DES

HERE = Path(__file__).resolve().parent
HEADER = HERE / 'forceunlock_v2.h'
VERSIONS = ['500', '502', '504', '506', '506mx', '512', '600', '602', '604', '606', '610', '612']

GNU = {'cc': ['arm-none-eabi-gcc', '-c'],
       'ld': ['arm-none-eabi-ld'],
       'objcopy': ['arm-none-eabi-objcopy']}
CLANG = {'cc': ['clang', '--target=arm-none-eabi', '-c'],
         'ld': ['ld.lld', '-m', 'armelf'],
         'objcopy': ['llvm-objcopy']}


def assemble(version, tools, tmp):
    src = HERE / (version + '.S')
    load = int(re.search(r'^\s*\.equ\s+LOAD,\s*(0x[0-9A-Fa-f]+)', src.read_text(), re.M).group(1), 16)
    obj, elf, raw = (Path(tmp) / (version + ext) for ext in ('.o', '.elf', '.bin'))
    subprocess.run(tools['cc'] + ['-mcpu=arm7tdmi', '-I', str(HERE), str(src), '-o', str(obj)], check=True)
    subprocess.run(tools['ld'] + ['-Ttext=0x%08x' % load, '--entry=body_start', str(obj), '-o', str(elf)], check=True)
    subprocess.run(tools['objcopy'] + ['-O', 'binary', str(elf), str(raw)], check=True)
    block = raw.read_bytes()
    if len(block) > 0xD8:
        sys.exit('%s: %d bytes, the patch block holds 216' % (version, len(block)))
    table0 = struct.unpack_from('<I', block, 0x20)[0]
    if not load + 0x24 <= table0 < load + 0xD8:
        sys.exit('%s: svc table[0] 0x%08x is outside the body' % (version, table0))
    return block.ljust(0xD8, b'\0')


def encrypt(block, key):
    ct = DES.new(key, DES.MODE_ECB).encrypt(block)
    out = bytearray(0xE0)
    out[0x00:0x6E] = ct[0x00:0x6E]
    out[0x70:0xDA] = ct[0x6E:0xD8]
    addr_sum = sum(struct.unpack_from('<4I', block)) & 0xFFFFFFFF
    struct.pack_into('<I', out, 0xDA, ~addr_sum & 0xFFFFFFFF)
    for half in (0x00, 0x70):
        out[half + 0x6F] = ~sum(out[half:half + 0x6E]) & 0xFF
    return bytes(out)


def header(patches):
    lines = ['/* Generated by forceunlock_v2/build.py from forceunlock_v2/*.S. Do not edit. */', '',
             '// clang-format off', '']
    for version, data in patches.items():
        lines.append('static const uint8_t forceunlock_v2_%s[] = {' % version)
        for i in range(0, len(data), 8):
            lines.append('    ' + ', '.join('0x%02x' % b for b in data[i:i + 8]) + ',')
        lines += ['};', '']
    lines += ['// clang-format on', '']
    return '\n'.join(lines)


def main():
    key = bytes.fromhex(os.environ.get('MECHA_PATCH_KEY', ''))
    if len(key) != 8:
        sys.exit('set MECHA_PATCH_KEY to the 8-byte NVRAM patch key (16 hex digits)')
    tools = CLANG if '--clang' in sys.argv else GNU
    tools = {k: [shutil.which(v[0]) or v[0]] + v[1:] for k, v in tools.items()}
    with tempfile.TemporaryDirectory() as tmp:
        patches = {v: encrypt(assemble(v, tools, tmp), key) for v in VERSIONS}
    text = header(patches)
    if '--check' in sys.argv:
        if HEADER.read_text() != text:
            sys.exit('forceunlock_v2.h does not match the sources')
        print('forceunlock_v2.h matches the sources')
    else:
        HEADER.write_text(text, newline='\n')
        print('wrote', HEADER.name)


if __name__ == '__main__':
    main()
